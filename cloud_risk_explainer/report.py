"""Assemble the final report (Markdown, and optional HTML) from scored findings.

Pure string building, no LLM and no network: fully testable offline.
"""
import html as _html

from .score import SEVERITY_WEIGHT, SIGNAL_LABEL, SIGNAL_WEIGHT, severity_counts

AI_DISCLAIMER = (
    "> **AI-assisted report.** The executive summary and the per-finding "
    "\"why this matters\" / remediation narrative are **drafted by an LLM** and may "
    "contain errors. The risk scores, ranking and exposure signals are computed "
    "deterministically. A qualified human must review this before acting on it. "
    "This is a triage and drafting aid, not a compliance attestation."
)


def _signal_labels(signals):
    return ", ".join(SIGNAL_LABEL[s] for s in signals) or "-"


def _truncate(text, n=70):
    text = (text or "").replace("\n", " ").strip()
    return text if len(text) <= n else text[: n - 1] + "…"


def _methodology_md():
    sev = " · ".join(f"{k} {v}" for k, v in SEVERITY_WEIGHT.items())
    sig = " · ".join(f"{SIGNAL_LABEL[k]} +{v}" for k, v in SIGNAL_WEIGHT.items())
    return (
        "**How the risk score is computed (deterministic):** "
        "`score = severity_weight x (1 + sum of exposure signal weights)`.\n\n"
        f"- Severity weight: {sev}\n"
        f"- Exposure multiplier adds: {sig}\n\n"
        "Exposure amplifies severity, so a publicly reachable critical finding "
        "always ranks above an internal-only critical."
    )


def build_markdown(scored, narrative, meta) -> str:
    """Return the full report as a Markdown string."""
    counts = severity_counts(scored)
    lines = []
    a = lines.append

    a("# Cloud Risk Report")
    a("")
    a(f"*Source: `{meta.get('source', 'n/a')}` · format: {meta.get('format', 'n/a')} "
      f"· {meta.get('total', len(scored))} findings · generated {meta.get('generated_at', '')}*")
    a("")
    a(AI_DISCLAIMER)
    a("")

    a("## Executive summary")
    a("")
    if not narrative.get("llm_available", False):
        a("> _Narrative generated without an LLM (endpoint unavailable); "
          "deterministic fallback text shown._")
        a("")
    a(narrative.get("executive_summary", "").strip() or "_No summary available._")
    a("")

    a("## Risk overview")
    a("")
    a("| Severity | Count |")
    a("|---|---|")
    for sev in SEVERITY_WEIGHT:
        a(f"| {sev.title()} | {counts.get(sev, 0)} |")
    a(f"| **Total** | **{len(scored)}** |")
    a("")

    a("## Prioritized findings")
    a("")
    a("| # | Score | Band | Severity | Service | Finding | Resource | Exposure |")
    a("|---|---|---|---|---|---|---|---|")
    for s in scored:
        f = s.finding
        a(f"| {s.rank} | {s.score} | {s.band} | {f.severity.title()} | {f.service} | "
          f"{_truncate(f.title)} | `{_truncate(f.resource, 44)}` | {_signal_labels(s.signals)} |")
    a("")

    a("## Finding detail")
    a("")
    llm_on = narrative.get("llm_available", False)
    per = narrative.get("per_finding", {}) if llm_on else {}
    for s in scored:
        f = s.finding
        a(f"### {s.rank}. {f.title}")
        a("")
        a(f"- **Risk score:** {s.score} ({s.band}) &nbsp;|&nbsp; **Severity:** {f.severity.title()} "
          f"&nbsp;|&nbsp; **Service:** {f.service}")
        a(f"- **Resource:** `{f.resource or 'n/a'}`")
        a(f"- **Exposure signals:** {_signal_labels(s.signals)}")
        a(f"- **Finding ID:** `{f.id}`")
        a("")
        if f.description:
            a(f.description)
            a("")
        detail = per.get(f.id)
        if detail:
            a("**Why this matters** _(AI-drafted)_")
            a("")
            a(detail.get("why", "").strip() or "_n/a_")
            a("")
            if detail.get("steps", "").strip():
                a("**Remediation steps** _(AI-drafted, verify before applying)_")
                a("")
                a(detail["steps"].strip())
                a("")
        elif f.remediation_hint:
            a(f"**Remediation hint:** {f.remediation_hint}")
            a("")

    a("---")
    a("")
    a(_methodology_md())
    a("")
    a("_Generated by [cloud-risk-explainer]"
      "(https://github.com/aminafara123/cloud-risk-explainer). "
      "AI-assisted narrative, human review required._")
    a("")
    return "\n".join(lines)


def build_html(scored, narrative, meta) -> str:
    """Minimal self-contained HTML version, built from the same structured data."""
    counts = severity_counts(scored)
    e = _html.escape

    rows = "\n".join(
        f"<tr><td>{s.rank}</td><td>{s.score}</td><td>{s.band}</td>"
        f"<td>{e(s.finding.severity.title())}</td><td>{e(s.finding.service)}</td>"
        f"<td>{e(s.finding.title)}</td><td><code>{e(s.finding.resource)}</code></td>"
        f"<td>{e(_signal_labels(s.signals))}</td></tr>"
        for s in scored
    )
    sev_rows = "\n".join(
        f"<tr><td>{sev.title()}</td><td>{counts.get(sev, 0)}</td></tr>"
        for sev in SEVERITY_WEIGHT
    )

    per = narrative.get("per_finding", {}) if narrative.get("llm_available") else {}
    details = []
    for s in scored:
        f = s.finding
        block = [f"<h3>{s.rank}. {e(f.title)}</h3>",
                 f"<p class='meta'>Risk {s.score} ({s.band}) · {e(f.severity.title())} · "
                 f"{e(f.service)} · <code>{e(f.resource)}</code> · "
                 f"Exposure: {e(_signal_labels(s.signals))}</p>"]
        if f.description:
            block.append(f"<p>{e(f.description)}</p>")
        d = per.get(f.id)
        if d:
            block.append("<p><strong>Why this matters</strong> <em>(AI-drafted)</em><br>"
                         f"{e(d.get('why', ''))}</p>")
            if d.get("steps", "").strip():
                block.append("<p><strong>Remediation steps</strong> "
                             "<em>(AI-drafted, verify before applying)</em></p>"
                             f"<pre>{e(d['steps'])}</pre>")
        elif f.remediation_hint:
            block.append(f"<p><strong>Remediation hint:</strong> {e(f.remediation_hint)}</p>")
        details.append("\n".join(block))

    fallback_note = ("" if narrative.get("llm_available") else
                     "<p class='warn'>Narrative generated without an LLM (endpoint "
                     "unavailable); deterministic fallback text shown.</p>")

    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Cloud Risk Report</title>
<style>
  body{{font:16px/1.6 system-ui,sans-serif;max-width:900px;margin:2rem auto;padding:0 1rem;color:#1a1a1a}}
  h1{{margin-bottom:.2rem}} .sub{{color:#666;font-size:.9rem}}
  table{{border-collapse:collapse;width:100%;margin:1rem 0;font-size:.9rem}}
  th,td{{border:1px solid #ddd;padding:.4rem .6rem;text-align:left;vertical-align:top}}
  th{{background:#f4f4f4}} code{{font-size:.85em}}
  .disclaimer{{background:#fff8e1;border-left:4px solid #e6a700;padding:.8rem 1rem;margin:1rem 0}}
  .warn{{color:#a15c00}} .meta{{color:#666;font-size:.85rem}}
  pre{{background:#f6f8fa;padding:.8rem;overflow-x:auto;white-space:pre-wrap}}
  @media (prefers-color-scheme: dark){{
    body{{background:#121212;color:#e6e6e6}} th{{background:#1e1e1e}}
    th,td{{border-color:#333}} .disclaimer{{background:#2a2410}} pre{{background:#1e1e1e}}
  }}
</style></head><body>
<h1>Cloud Risk Report</h1>
<p class="sub">Source: <code>{e(str(meta.get('source', 'n/a')))}</code> · format: {e(str(meta.get('format', 'n/a')))}
 · {len(scored)} findings · generated {e(str(meta.get('generated_at', '')))}</p>
<div class="disclaimer"><strong>AI-assisted report.</strong> The summary and per-finding narrative
are drafted by an LLM and may contain errors. Scores and ranking are deterministic. A qualified
human must review this before acting. Triage/drafting aid, not a compliance attestation.</div>
<h2>Executive summary</h2>
{fallback_note}
<p>{e(narrative.get('executive_summary', '')).replace(chr(10), '<br>')}</p>
<h2>Risk overview</h2>
<table><tr><th>Severity</th><th>Count</th></tr>
{sev_rows}
<tr><td><strong>Total</strong></td><td><strong>{len(scored)}</strong></td></tr></table>
<h2>Prioritized findings</h2>
<table><tr><th>#</th><th>Score</th><th>Band</th><th>Severity</th><th>Service</th>
<th>Finding</th><th>Resource</th><th>Exposure</th></tr>
{rows}
</table>
<h2>Finding detail</h2>
{"<hr>".join(details)}
<hr>
<p class="meta">Generated by cloud-risk-explainer. AI-assisted narrative, human review required.</p>
</body></html>
"""
